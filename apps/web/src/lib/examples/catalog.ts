export const EXAMPLE_CATEGORY_COUNTS: Record<ExampleCategory, number> = {
  iterativos: iterativeExamples.length,
  "divide-y-venceras": divideAndConquerExamples.length,
  "resta-y-venceras": decreaseAndConquerExamples.length,
  "resta-y-seras-vencido": decreaseByOneExamples.length,
};

export const isRecursiveCategory = (category: ExampleCategory): boolean =>
  category !== "iterativos";

export const isExampleCategory = (value: string): value is ExampleCategory =>
  EXAMPLE_CATEGORY_ORDER.includes(value as ExampleCategory);

const normalize = (value: string): string =>
  value
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .trim();

export const sortByLocalizedTitle = (
  items: ExampleCatalogItem[],
  locale: ExampleLocale,
): ExampleCatalogItem[] =>
  [...items].sort((left, right) =>
    left.copy[locale].title.localeCompare(right.copy[locale].title, locale),
  );

export const getEnabledExamples = (
  items: ExampleCatalogItem[] = examplesCatalog,
): ExampleCatalogItem[] => items.filter((item) => item.enabled);

export const getExamplesByCategory = (
  category: ExampleCategory,
  options?: { enabledOnly?: boolean; locale?: ExampleLocale },
): ExampleCatalogItem[] => {
  const enabledOnly = options?.enabledOnly ?? true;
  const locale = options?.locale ?? "es";
  const subset = examplesCatalog.filter(
    (item) => item.category === category && (!enabledOnly || item.enabled),
  );
  return sortByLocalizedTitle(subset, locale);
};

export const filterByMethods = (
  items: ExampleCatalogItem[],
  methods: RecursiveMethodBadge[],
): ExampleCatalogItem[] => {
  if (methods.length === 0) {
    return items;
  }

  return items.filter((item) =>
    item.verifiedMethods.some((method) => methods.includes(method)),
  );
};

export const searchExamples = (
  items: ExampleCatalogItem[],
  locale: ExampleLocale,
  query: string,
): ExampleCatalogItem[] => {
  const normalizedQuery = normalize(query);
  if (!normalizedQuery) {
    return items;
  }

  return items.filter((item) => {
    const copy = item.copy[locale];
    const haystack = [copy.title, copy.summary, ...copy.tags]
      .map(normalize)
      .join(" ");

    return haystack.includes(normalizedQuery);
  });
};

export const getCategoryMeta = (
  category: ExampleCategory,
): ExampleCategoryMeta => EXAMPLE_CATEGORY_META[category];

export const getCategoryTotals = (
  category: ExampleCategory,
): {
  total: number;
  enabled: number;
} => ({
  total: examplesCatalog.filter((item) => item.category === category).length,
  enabled: examplesCatalog.filter(
    (item) => item.category === category && item.enabled,
  ).length,
});

export const findExampleBySlug = (
  slug: string,
): ExampleCatalogItem | undefined =>
  examplesCatalog.find((item) => item.slug === slug);

export const getMethodTranslationKey = (method: RecursiveMethodBadge): string =>
  EXAMPLE_METHOD_TRANSLATION_KEYS[method];
